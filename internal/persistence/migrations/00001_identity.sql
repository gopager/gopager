    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id = 1),
    access_revision bigint NOT NULL DEFAULT 1 CHECK (access_revision > 0),
    bootstrapped boolean NOT NULL DEFAULT false
