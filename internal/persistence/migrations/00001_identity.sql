CREATE TABLE identity_accounts (
    id uuid PRIMARY KEY,
    revision bigint NOT NULL DEFAULT 1 CHECK (revision > 0),
    kind varchar NOT NULL CHECK (kind IN ('human', 'technical', 'guest')),
    state varchar NOT NULL DEFAULT 'active' CHECK (state IN ('active', 'suspended', 'deleting', 'deleted')),
    username text,
    username_key text UNIQUE,
    password_hash text,
    display_name text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL,
    deleted_at timestamptz,
    CHECK ((username IS NULL) = (username_key IS NULL)),
    CHECK (kind = 'human' OR password_hash IS NULL)
);
CREATE UNIQUE INDEX identity_single_guest ON identity_accounts (kind) WHERE kind = 'guest';

CREATE TABLE identity_user_groups (
    id uuid PRIMARY KEY,
    revision bigint NOT NULL DEFAULT 1 CHECK (revision > 0),
    name varchar(256) NOT NULL CHECK (name <> '')
);

CREATE TABLE identity_memberships (
    id uuid PRIMARY KEY,
    revision bigint NOT NULL DEFAULT 1 CHECK (revision > 0),
    account_id uuid NOT NULL REFERENCES identity_accounts(id),
    group_id uuid NOT NULL REFERENCES identity_user_groups(id),
    UNIQUE (account_id, group_id)
);

CREATE TABLE identity_grants (
    id uuid PRIMARY KEY,
    revision bigint NOT NULL DEFAULT 1 CHECK (revision > 0),
    subject_id uuid NOT NULL,
    subject_kind varchar NOT NULL CHECK (subject_kind IN ('principal', 'userGroup')),
    actions jsonb NOT NULL,
    scope jsonb NOT NULL,
    -- Unpublished legacy column; retained but not used for authorization (global field permissions own it).
    field_names jsonb NOT NULL DEFAULT '[]'::jsonb,
    max_age_seconds bigint CHECK (max_age_seconds >= 0),
    delegable boolean NOT NULL DEFAULT false
);
CREATE INDEX grant_subject_id_subject_kind ON identity_grants (subject_id, subject_kind);

CREATE TABLE identity_credentials (
    id uuid PRIMARY KEY,
    revision bigint NOT NULL DEFAULT 1 CHECK (revision > 0),
    account_id uuid NOT NULL REFERENCES identity_accounts(id),
    kind varchar NOT NULL CHECK (kind IN ('session', 'accessKey', 'recovery')),
    secret_hash bytea NOT NULL UNIQUE CHECK (octet_length(secret_hash) = 32),
    csrf_token varchar,
    restrictions jsonb,
    created_at timestamptz NOT NULL,
    last_used_at timestamptz NOT NULL,
    expires_at timestamptz,
    revoked_at timestamptz,
    consumed_at timestamptz
);
CREATE INDEX credential_account_id_kind ON identity_credentials (account_id, kind);

